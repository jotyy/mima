// Writes src/bundled-migrations.ts from src/migrations, so the Worker can apply the
// migrations itself (see src/migrate.ts). `bun run db:generate` runs it after drizzle-kit;
// a test fails when the two disagree.
import { spawnSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import path from "node:path";

import { readMigrations } from "./read-migrations";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "src/bundled-migrations.ts");
const migrations = await readMigrations(path.join(root, "src/migrations"));

await writeFile(
	out,
	`// Generated by scripts/bundle-migrations.ts from src/migrations. Don't edit it by hand:
// \`bun run db:generate\` writes it again.
export const migrations: readonly {
	name: string;
	hash: string;
	sql: string;
}[] = ${JSON.stringify(migrations)};
`,
);
spawnSync("bunx", ["biome", "format", "--write", out], { stdio: "inherit" });
console.log(
	`Bundled ${migrations.length} migrations into ${path.relative(root, out)}`,
);
